#!/bin/sh
set -e

CONF_FILE="/etc/chrony/chrony.conf"

# Default to common pools if NTP_SERVERS is empty
if [ -z "$NTP_SERVERS" ]; then
  NTP_SERVERS="0.pool.ntp.org 1.pool.ntp.org"
fi

# Default to allowing all clients if CHRONY_ALLOW_LIST is empty
if [ -z "$CHRONY_ALLOW_LIST" ]; then
  CHRONY_ALLOW_LIST="all"
fi

# Generate /etc/chrony/chrony.conf cleanly on every start/restart
{
  echo "# Generated by entrypoint.sh"
  for s in $NTP_SERVERS; do
    echo "server $s iburst"
  done
  echo ""
  echo "driftfile /var/lib/chrony/chrony.drift"
  echo "logdir /var/log/chrony"
  echo "makestep 1.0 3"
  echo "rtcsync"
  echo ""
  for net in $CHRONY_ALLOW_LIST; do
    echo "allow $net"
  done
  echo ""
  echo "local stratum 10"
} > "$CONF_FILE"

# Remove stale PID file in case the container was Previously stopped uncleanly
rm -f /run/chrony/chronyd.pid /var/run/chrony/chronyd.pid

# If NOCLOCK=true is set, pass -x so chronyd does not attempt to adjust the host clock
EXTRA_ARGS=""
if [ "$NOCLOCK" = "true" ] || [ "$NOCLOCK" = "1" ]; then
  EXTRA_ARGS="-x"
fi

# Start chronyd in the foreground (-d)
exec /usr/sbin/chronyd -d $EXTRA_ARGS
